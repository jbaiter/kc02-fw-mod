#!/usr/bin/env python3
"""Generate the checked-in antialiased ASCII font (Pillow + DejaVu Sans)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = Path('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf')

def generate():
    lines = ['/* Generated by tools/font.py. DejaVu license: ../LICENSE.font */',
             'typedef struct { unsigned off; unsigned char w, advance; } Glyph;']
    for label, size, height in [('small', 11, 15), ('large', 18, 24)]:
        font = ImageFont.truetype(str(FONT), size)
        glyphs, pixels = [], []
        for code in range(32, 127):
            text = chr(code)
            width = max(1, font.getbbox(text)[2])
            glyphs.append((len(pixels), width, round(font.getlength(text))))
            im = Image.new('L', (width, height))
            ImageDraw.Draw(im).text((0, 0), text, font=font, fill=255)
            pixels.extend(im.tobytes())
        lines += [f'static const Glyph {label}_glyphs[] = {{',
                  ',\n'.join('{%d,%d,%d}' % g for g in glyphs), '};',
                  f'static const unsigned char {label}_pixels[] = {{']
        lines += [','.join(map(str, pixels[i:i+32])) + ',' for i in range(0, len(pixels), 32)]
        lines += ['};']
    (ROOT / 'src/font.inc').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
    generate()
